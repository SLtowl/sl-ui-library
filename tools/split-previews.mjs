// Split the legacy preview bundle for the catalog's on-demand loader.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';

const publicRoot=fileURLToPath(new URL('../public/',import.meta.url));
const source=await readFile(path.join(publicRoot,'preview-data.js'),'utf8');
const lines=source.split('\n');
const exportAt=lines.findIndex(l=>l.startsWith('export const previews = {'));
if(exportAt<0)throw Error('No previews export found');

// Top-level declarations are written at column 0 as `const styleN =`, `const apiN = (() => {`, `const nameDemo = (() => {` or `function frameApiN(`.
// The code inside those wrappers is not indented, so only these names count as starts.
const START=/^(?:const (style\d+|api\d+|[A-Za-z]+Demo) = |function (frameApi\d+)\()/;
const segments=new Map();let name=null,from=0;
const close=to=>{if(name)segments.set(name,lines.slice(from,to).join('\n'))};
for(let i=0;i<exportAt;i++){const m=lines[i].match(START);if(m){close(i);name=m[1]||m[2];from=i}}
close(exportAt);
// Each piece must be valid code on its own, or a boundary was misread.
for(const [n,text] of segments){try{new Function(text)}catch(e){throw Error(`Segment ${n} does not parse: ${e.message}`)}}

const known=[...segments.keys()],order=new Map(known.map((n,i)=>[n,i]));
const refs=text=>[...new Set(text.match(/\b(style\d+|api\d+|frameApi\d+|[A-Za-z]+Demo)\b/g)||[])].filter(n=>segments.has(n));
const deps=new Map(known.map(n=>[n,refs(segments.get(n)).filter(d=>d!==n)]));
const closure=start=>{const seen=new Set(),walk=n=>{if(seen.has(n))return;seen.add(n);for(const d of deps.get(n))walk(d)};start.forEach(walk);return [...seen].sort((a,b)=>order.get(a)-order.get(b))};

const entries=[];
for(let i=exportAt+1;i<lines.length;i++){
  const line=lines[i];if(line==='};')break;if(!line.trim())continue;
  const m=line.match(/^"([^"]+)": (\{.*\}),?$/);if(!m)throw Error('Unexpected previews line '+(i+1));
  if(!/^[a-z0-9-]+$/.test(m[1]))throw Error('Unsafe preview name '+m[1]);
  entries.push([m[1],m[2]]);
}

const out=path.join(publicRoot,'previews');
await mkdir(out,{recursive:true});
const banner='// Generated by tools/split-previews.mjs. Do not edit by hand.\n';
for(const [n,body] of entries){
  const used=closure(refs(body));
  await writeFile(path.join(out,n+'.js'),banner+used.map(u=>segments.get(u)).join('\n')+`\nexport default ${body};\n`);
}

// Which previews exist as files, and which presentation variants are built on top of them.
const {variants}=await import(pathToFileURL(path.join(publicRoot,'experiments/library-shell/batch-presentations.mjs')).href);
const batch=Object.fromEntries(variants.map(v=>[v.variant,v.base]));
await writeFile(path.join(out,'index.js'),banner+`export const names=new Set(${JSON.stringify(entries.map(e=>e[0]))});\nexport const batch=${JSON.stringify(batch)};\n`);
console.log(`Split ${entries.length} previews from ${segments.size} shared pieces into public/previews/`);
